import pytest

from app.chatbot.exceptions import GenerationError
from app.chatbot.models import Chunk, RetrievedChunk
from app.chatbot.service import MedicalAssistance


class FakeLLM:
    """
    Fake LLM class to simulate the behavior of the LLM for testing purposes.
    """

    def __init__(self):
        self.received_messages = None

    def generate(self, messages):
        self.received_messages = messages
        return "RESPUESTA_FAKE"


class FakeRetriever:
    """
    Fake Retriever class to simulate successful retrieval.
    """

    def __init__(self):
        self.received_query = None

    def retrieve(self, query):
        self.received_query = query

        chunk = Chunk(
            chunk_id="fever_000",
            document_id="fever",
            title="Fever",
            source="Test Medical Source",
            source_url="https://example.com/fever",
            section="Overview",
            content="CONTEXTO_FAKE",
        )

        return [
            RetrievedChunk(
                chunk=chunk,
                score=0.8,
            )
        ]


class FakeEmptyRetriever:
    """
    Fake Retriever that simulates no relevant context being found.
    """

    def retrieve(self, query):
        return []


class FailingLLM:
    """
    Fake LLM that simulates a generation failure.
    """

    def generate(self, messages):
        raise RuntimeError("LLM failure")


def test_service_returns_llm_response():
    """
    Check that the service returns the response generated by the LLM.
    """
    # Create the bot with the fake LLM and Retriever (Arrange)
    llm = FakeLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    # Get the response from the bot (Act)
    # As it is a fake retriever, it does not matter the content
    # of the query, it will always return the same context, and
    # the fake LLM will always return the same response.
    result = bot.generate_response([{"role": "user", "content": "Tengo fiebre"}])

    # Check that the generated response is returned
    assert result.response == "RESPUESTA_FAKE"

    # Check that provenance is preserved
    assert len(result.sources) == 1
    assert result.sources[0].title == "Fever"
    assert result.sources[0].section == "Overview"
    assert result.sources[0].source == "Test Medical Source"
    assert result.sources[0].source_url == "https://example.com/fever"


def test_service_builds_structured_messages():
    """
    Test that the service separates system instructions,
    retrieved evidence, and the user question.
    """
    llm = FakeLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    bot.generate_response([
        {"role": "user", "content": "Tengo fiebre"}
    ])

    messages = llm.received_messages

    # Verify the message structure
    assert len(messages) == 2

    assert messages[0]["role"] == "system"
    assert messages[1]["role"] == "user"

    # Verify system instructions
    system_content = messages[0]["content"]

    assert "Spanish" in system_content
    assert "retrieved evidence" in system_content

    # Retrieved data should not appear in system instructions
    assert "CONTEXTO_FAKE" not in system_content

    # Verify the user prompt
    user_content = messages[1]["content"]

    assert "<retrieved_evidence>" in user_content
    assert "</retrieved_evidence>" in user_content

    assert "<question>" in user_content
    assert "</question>" in user_content

    # Verify evidence and question content
    assert "CONTEXTO_FAKE" in user_content
    assert "Tengo fiebre" in user_content

    # Verify chunk identification
    assert "Chunk ID: fever_000" in user_content


def test_service_returns_fallback_without_context():
    """
    Test that the service returns a deterministic fallback
    without invoking the LLM when no evidence is retrieved.
    """
    llm = FakeLLM()
    retriever = FakeEmptyRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    result = bot.generate_response([
        {
            "role": "user",
            "content": "Tengo un síntoma desconocido",
        }
    ])

    # Verify the fallback response
    assert result.response == (
        "No dispongo de información suficiente en la base "
        "de conocimientos para responder esa pregunta."
    )

    # No sources should be returned
    assert result.sources == []

    # The LLM must not be invoked
    assert llm.received_messages is None


