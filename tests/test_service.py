import pytest

from app.chatbot.exceptions import GenerationError
from app.chatbot.models import Chunk, RetrievedChunk
from app.chatbot.service import MedicalAssistance


class FakeLLM:
    """
    Fake LLM class to simulate the behavior of the LLM for testing purposes.
    """

    def __init__(self):
        self.received_messages = None

    def generate(self, messages):
        self.received_messages = messages
        return "RESPUESTA_FAKE"


class FakeRetriever:
    """
    Fake Retriever class to simulate successful retrieval.
    """

    def __init__(self):
        self.received_query = None

    def retrieve(self, query):
        self.received_query = query

        chunk = Chunk(
            chunk_id="fever_000",
            document_id="fever",
            title="Fever",
            source="Test Medical Source",
            source_url="https://example.com/fever",
            section="Overview",
            content="CONTEXTO_FAKE",
        )

        return [
            RetrievedChunk(
                chunk=chunk,
                score=0.8,
            )
        ]


class FakeEmptyRetriever:
    """
    Fake Retriever that simulates no relevant context being found.
    """

    def retrieve(self, query):
        return []


class FailingLLM:
    """
    Fake LLM that simulates a generation failure.
    """

    def generate(self, messages):
        raise RuntimeError("LLM failure")


def test_service_returns_llm_response():
    """
    Check that the service returns the response generated by the LLM.
    """
    # Create the bot with the fake LLM and Retriever (Arrange)
    llm = FakeLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    # Get the response from the bot (Act)
    # As it is a fake retriever, it does not matter the content
    # of the query, it will always return the same context, and
    # the fake LLM will always return the same response.
    result = bot.generate_response([{"role": "user", "content": "Tengo fiebre"}])

    # Check that the generated response is returned
    assert result.response == "RESPUESTA_FAKE"

    # Check that provenance is preserved
    assert len(result.sources) == 1
    assert result.sources[0].title == "Fever"
    assert result.sources[0].section == "Overview"
    assert result.sources[0].source == "Test Medical Source"
    assert result.sources[0].source_url == "https://example.com/fever"


def test_service_uses_retrieved_context():
    """
    Check that the service uses the retrieved context.
    """
    llm = FakeLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    bot.generate_response([{"role": "user", "content": "Tengo fiebre"}])

    # Check that the retrieved context is included in the messages sent to the LLM
    assert "CONTEXTO_FAKE" in llm.received_messages[1]["content"]
    # Check that the original user message is also included in the messages sent to the LLM
    assert "Tengo fiebre" in llm.received_messages[1]["content"]


def test_service_uses_fallback_when_no_context_is_found():
    """
    Check that the service uses a fallback when no relevant context is found.
    """
    llm = FakeLLM()
    retriever = FakeEmptyRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    result = bot.generate_response(
        [{"role": "user", "content": "Tengo un síntoma desconocido"}]
    )

    # Check that the response is generated even when no context is found
    assert result.sources == []

    # Check that the fallback message is included in the messages sent to the LLM
    assert (
        "Lo siento, no hay información al respecto"
        in llm.received_messages[1]["content"]
    )
    # Check that the original user message is included in the messages sent to the LLM
    assert "Tengo un síntoma desconocido" in llm.received_messages[1]["content"]


def test_service_sends_user_query_to_retriever():
    """
    Check that the service sends the user's query to the retriever.
    """
    llm = FakeLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    bot.generate_response([{"role": "user", "content": "Tengo fiebre"}])
    # Check that the retriever received the correct user query
    assert retriever.received_query == "Tengo fiebre"


def test_service_translates_llm_error():
    """
    Test that the service translates errors from the LLM.
    """
    llm = FailingLLM()
    retriever = FakeRetriever()

    bot = MedicalAssistance(
        llm=llm,
        retriever=retriever,
    )

    # Check that the service raises a GenerationError when the LLM fails
    with pytest.raises(GenerationError):
        bot.generate_response([{"role": "user", "content": "Tengo fiebre"}])


def test_build_context_formats_retrieved_chunks():
    """
    Test that _build_context formats retrieved chunks as structured
    context for the LLM.
    """
    # Create sample retrieved chunks
    retrieved_chunks = [
        RetrievedChunk(
            chunk=Chunk(
                chunk_id="fever_000",
                document_id="fever",
                title="Fever",
                source="Test Medical Source",
                source_url="https://example.com/fever",
                section="Overview",
                content="Fever overview content.",
            ),
            score=0.8,
        ),
        RetrievedChunk(
            chunk=Chunk(
                chunk_id="fever_001",
                document_id="fever",
                title="Fever",
                source="Test Medical Source",
                source_url="https://example.com/fever",
                section="Common Causes",
                content="Fever causes content.",
            ),
            score=0.7,
        ),
    ]

    # Create the service without real dependencies
    bot = MedicalAssistance(
        llm=None,
        retriever=None,
    )

    # Build the context
    context = bot._build_context(retrieved_chunks)

    # Verify the first context block
    assert "[Context 1]" in context
    assert "Title: Fever" in context
    assert "Section: Overview" in context
    assert "Source: Test Medical Source" in context
    assert "Fever overview content." in context

    # Verify the second context block
    assert "[Context 2]" in context
    assert "Section: Common Causes" in context
    assert "Fever causes content." in context

    # Retrieval metadata that should not be exposed to the LLM
    assert "0.8" not in context
    assert "0.7" not in context
    assert "https://example.com/fever" not in context


def test_build_sources_returns_provenance_from_retrieved_chunks():
    """
    Test that _build_sources extracts provenance information
    from retrieved chunks.
    """
    # Create sample retrieved chunks
    retrieved_chunks = [
        RetrievedChunk(
            chunk=Chunk(
                chunk_id="fever_000",
                document_id="fever",
                title="Fever",
                source="Test Medical Source",
                source_url="https://example.com/fever",
                section="Overview",
                content="Fever overview content.",
            ),
            score=0.8,
        ),
        RetrievedChunk(
            chunk=Chunk(
                chunk_id="fever_001",
                document_id="fever",
                title="Fever",
                source="Test Medical Source",
                source_url="https://example.com/fever",
                section="Common Causes",
                content="Fever causes content.",
            ),
            score=0.7,
        ),
    ]

    # Create the service without real dependencies
    bot = MedicalAssistance(
        llm=None,
        retriever=None,
    )

    # Build the sources
    sources = bot._build_sources(retrieved_chunks)

    # Verify that the sources list has the correct length and content
    assert len(sources) == 2

    assert sources[0].title == "Fever"
    assert sources[0].section == "Overview"
    assert sources[0].source == "Test Medical Source"
    assert sources[0].source_url == "https://example.com/fever"

    assert sources[1].title == "Fever"
    assert sources[1].section == "Common Causes"
