"""
Module containing the MedicalAssistance class.

Classes:
    - MedicalAssistance: Class that represents a chatbot for medical assistance.
"""

from app.chatbot.exceptions import GenerationError
from app.chatbot.models import RetrievedChunk, Source


class MedicalAssistance:
    """
    Class that represents a chatbot for medical assistance.

    This class handles the chatbot to generate responses.
    """

    def __init__(
        self,
        llm,
        retriever,
    ):
        """
        Initialize a new bot.

        Attributes
        ----------
        llm : obj
            The llm we use to generate responses given the messages.
        retriever : obj
            The retriever used to manage the messages.
        """
        self.llm = llm
        self.retriever = retriever

    def _build_context(
        self,
        retrieved_chunks: list[RetrievedChunk],
    ) -> str:
        """
        Build the context provided to the LLM from retrieved chunks.

        Parameters
        ----------
        retrieved_chunks : list[RetrievedChunk]
            Ranked chunks returned by the retriever.

        Returns
        -------
        str
            Structured context for the language model.
        """
        # Build a structured context from the retrieved chunks
        context_blocks = []

        # Iterate over the retrieved chunks and format them
        for index, result in enumerate(retrieved_chunks, start=1):
            block = (
                f"[Context {index}]\n"
                f"Title: {result.chunk.title}\n"
                f"Section: {result.chunk.section}\n"
                f"Source: {result.chunk.source}\n"
                f"Content:\n"
                f"{result.chunk.content}"
            )
            context_blocks.append(block)

        # Join the context blocks with double newlines for clarity
        return "\n\n".join(context_blocks)

    def _build_sources(
        self,
        retrieved_chunks: list[RetrievedChunk],
    ) -> list[Source]:
        """
        Build provenance information from retrieved chunks.

        Parameters
        ----------
        retrieved_chunks : list[RetrievedChunk]
            Ranked chunks returned by the retriever.

        Returns
        -------
        list[Source]
            Sources associated with the retrieved chunks.
        """
        sources = []

        for result in retrieved_chunks:
            chunk = result.chunk

            sources.append(
                Source(
                    title=chunk.title,
                    section=chunk.section,
                    source=chunk.source,
                    source_url=chunk.source_url,
                )
            )

        return sources

    def generate_response(self, chat_history: list[dict[str, str]]):
        """
        Generate a response given the chat history and the medical context.

        This method performs:
        1. Semantic retrieval using the injected retriever
        2. Prompt construction
        3. LLM generative inference
        Parameters
        ----------
        chat_history : List[Dict[str, str]]
            Conversation history containing user and assistant messages.

        Returns
        -------
        response : str
            The response generated by the assistant.

        Notes
        -----
        The chat history is expected to follow this structure:
        [{"role": "user", "content": "Hola"},
        {"role": "assistant", "content": "Hola..."}]

        In this model we use a lightweight RAG pipeline over a plain text knowledge
        base. It is intentionally kept simple to allow fast iteration, and can be
        extended later if needed.
        """

        # Get the last query
        last_user_message = chat_history[-1]["content"]

        # RAG: Search only the relevant information
        retrieved_chunks = self.retriever.retrieve(last_user_message)

        if retrieved_chunks:
            context_to_use = self._build_context(retrieved_chunks)
        else:
            context_to_use = (
                "No hay información específica en la base de datos."
                "Respuesta obligatoria: Lo siento, no hay información al respecto."
            )

        full_prompt = f"""
        Instrucciones: Eres un asistente médico.
        Responde DIRECTAMENTE al paciente (usa "usted") basándote SOLO en el 
        TEXTO OFICIAL.
        Usa oraciones completas.
        Sé empático con el paciente.

        TEXTO OFICIAL:
        {context_to_use}

        ---
        PREGUNTA DEL PACIENTE: {last_user_message}
        
        TU RESPUESTA AL PACIENTE:
        """

        # Message structure
        messages = [
            {"role": "system", "content": "Eres un asistente médico útil y preciso."},
            {"role": "user", "content": full_prompt},
        ]

        try:
            response = self.llm.generate(messages)
        except Exception as error:
            raise GenerationError("Failed to generate LLM response.") from error

        return response
